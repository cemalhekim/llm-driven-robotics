function chapterplots(dirname) 
%--------------------------------------------------------------------------
% Festlegen aller Bilder
%--------------------------------------------------------------------------
dirarrid={ ,...
        'bild1' ,'1';...
        'bild2' ,'1';...
        'bild3' ,'1';...
        'bild4' ,'1';...
        'bild5' ,'1';...
        'bild6' ,'1';...
        'block' ,'3';...
    }; 
%--------------------------------------------------------------------------
cd(dirname);
for jj=1:length(dirarrid(:,1))
disp('.......................................................')
disp([': Erzeugen von ',char(dirarrid(jj,1))])
disp(':.....................................................:')
cd(char(dirarrid(jj,1)))
eval(([char(dirarrid(jj,1)),'(',num2str(char(dirarrid(jj,2))),')']));
cd ..
end
%--------------------------------------------------------------------------
cd ..
